#!/bin/bash

# Скрипт для отладки перезапуска станций

echo "========================================="
echo "ПРОВЕРКА СОСТОЯНИЯ СИСТЕМЫ"
echo "========================================="
echo ""

echo "1. Проверка запущенного сервера:"
ps aux | grep "node server.js" | grep -v grep || echo "❌ Сервер не запущен!"
echo ""

echo "2. Последние 50 строк логов сервера:"
echo "========================================="
tail -50 /tmp/server.log
echo "========================================="
echo ""

echo "3. Ищем ключевые события:"
echo "   - Отправка команд перезапуска:"
grep -c "ОТПРАВКА КОМАНД ПЕРЕЗАПУСКА" /tmp/server.log || echo "   0"

echo "   - Найдено соединений по IP:"
grep -c "НАЙДЕНО! Команда отправлена" /tmp/server.log || echo "   0"

echo "   - Подтверждения от станций:"
grep -c "подтвердила получение команды" /tmp/server.log || echo "   0"

echo ""
echo "4. Активные соединения (последние):"
grep "Socket.*IP=" /tmp/server.log | tail -10
echo ""

echo "========================================="
echo "Для очистки логов: echo '' > /tmp/server.log"
echo "Для просмотра в реальном времени: tail -f /tmp/server.log"
echo "========================================="

